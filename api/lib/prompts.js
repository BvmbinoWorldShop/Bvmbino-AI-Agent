  if (/!raw|--no-skill/i.test(lastMsg) || /don't use a template|just answer normally|pas de template/i.test(lastMsg)) return null;

  // Slash commands get priority — check last message only
  const slashMatch = lastMsg.match(/^\/([a-z]+)/i);

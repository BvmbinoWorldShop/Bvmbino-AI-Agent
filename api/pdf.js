// PDF generation using WeasyPrint-compatible approach via gotenberg or html2pdf service
// Uses PDFShift (free tier: 50 credits/month) — no server setup needed
export default async function handler(req, res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type');
  if (req.method === 'OPTIONS') return res.status(200).end();

  const apiKey = process.env.PDFSHIFT_KEY;
  if (!apiKey) return res.status(500).json({ error: 'PDFSHIFT_KEY not set. Get free key at pdfshift.io' });

  try {
    const body = typeof req.body === 'string' ? JSON.parse(req.body) : req.body;
    const { html, filename = 'bvmbino-export.pdf' } = body;
    if (!html) return res.status(400).json({ error: 'html required' });

    const styledHtml = `<!DOCTYPE html><html><head><meta charset="UTF-8">
    <style>
      body { font-family: 'Helvetica Neue', sans-serif; color: #1a1a2e; line-height: 1.7; padding: 48px; font-size: 13px; }
      h1 { font-size: 24px; font-weight: 700; color: #7C5CFC; margin-bottom: 4px; }
      h2 { font-size: 16px; font-weight: 600; color: #1a1a2e; border-bottom: 2px solid #7C5CFC; padding-bottom: 4px; margin-top: 24px; margin-bottom: 12px; }
      h3 { font-size: 13px; font-weight: 600; color: #7C5CFC; margin-bottom: 6px; }
      p { margin-bottom: 10px; }
      ul { padding-left: 20px; margin-bottom: 10px; }
      li { margin-bottom: 4px; }
      strong { color: #7C5CFC; }
      .header { border-bottom: 3px solid #7C5CFC; padding-bottom: 16px; margin-bottom: 24px; }
      .footer { margin-top: 40px; font-size: 10px; color: #888; border-top: 1px solid #eee; padding-top: 10px; }
    </style></head><body>${html}<div class="footer">Generated by Bvmbino AI Agent · ${new Date().toLocaleDateString()}</div></body></html>`;

    const response = await fetch('https://api.pdfshift.io/v3/convert/pdf', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': 'Basic ' + Buffer.from(`api:${apiKey}`).toString('base64'),
      },
      body: JSON.stringify({ source: styledHtml, landscape: false, use_print: false }),
    });

    if (!response.ok) {
      const err = await response.text();
      throw new Error(`PDFShift error: ${err}`);
    }

    const pdfBuffer = await response.arrayBuffer();
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);
    res.send(Buffer.from(pdfBuffer));
  } catch (err) {
    return res.status(500).json({ error: err.message });
  }
}

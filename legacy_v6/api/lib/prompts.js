export function detectSkill(messages, system) {
  const userMessages = (messages || []).filter(m => m.role === 'user');
  const recent = userMessages.slice(-3).map(m => m.content).join(' ').toLowerCase();
  const text = recent;

  if (/!raw|--no-skill/.test(text) || /don't use a template|just answer naturally/i.test(text)) return null;

  let matched = null;
  if (/\/content|write a post|make a caption|create content|instagram|linkedin post|reel script|social media post|créer contenu|publier|légende/i.test(text)) matched = 'content';
  else if (/\/proposal|write a proposal|create an offer|pitch a client|put together an offer for|send a quote to|offre|proposer|devis/i.test(text)) matched = 'proposal';
  else if (/\/sales|sales script|help me close|script de vente|vendre|fermer/i.test(text)) matched = 'sales';
  else if (/\/outreach|cold email|write a dm|write outreach|dm|email|prospection/i.test(text)) matched = 'outreach';
  else if (/\/course|build a course|curriculum|training program|formation|cours|programme/i.test(text)) matched = 'course';
  else if (/\/roadmap|revenue roadmap|plan my revenue|build my roadmap|feuille de route|plan d'action/i.test(text)) matched = 'roadmap';
  else if (/\/psych|analyze.*psychology|behavior|predict.*move|human.*nature|persuasion.*strategy|psychological|psychologie|comportement/i.test(text)) matched = 'psych';
  else if (/\/purgo|commercial cleaning|cleaning business|cleaning contract|nettoyage|propreté/i.test(text)) matched = 'purgo';
  else if (/\/enhance|enhance.*prompt|upgrade.*prompt|architect.*prompt|améliorer.*prompt|optimiser.*prompt/i.test(text)) matched = 'enhance';
  else if (/\/schedule|optimize.*schedule|plan.*week|time.?block|build.*schedule|emploi du temps|calendrier/i.test(text)) matched = 'schedule';
  else if (/\/imgprompt|\/vidprompt|image|photo|visuel|create.*prompt.*photo|générer.*image|professionnel.*image/i.test(text)) matched = 'imgprompt';
  else if (/\/writer|write.*book|write.*article|write.*blog|write.*chapter|write.*essay|ghostwrit|long.?form|rédiger|écrire/i.test(text)) matched = 'writer';
  else if (/\/budget|budget|expenses|income|money|cash|dépenses|revenus/i.test(text)) matched = 'budget';
  else if (/\/trade|crypto|market analysis|market analysis|analyse de marché/i.test(text)) matched = 'crypto';
  else if (/\/brand|brand voice|on brand|image de marque/i.test(text)) matched = 'brand';
  else if (/\/rule|enforce criteria|follow intent|check alignment|règle|alignement/i.test(text)) matched = 'rule';
  else if (/\/review|weekly review|how did i do this week|revue hebdomadaire/i.test(text)) matched = 'review';
  else if (/\/resume|cv|rédiger cv|ats/i.test(text)) matched = 'resume';
  else if (/\/campaign|campagne|créer pub|ad campaign/i.test(text)) matched = 'campaign';
  else if (/\/strategy|stratégie|audit business|growth/i.test(text)) matched = 'strategy';
  else if (/\/automate|make.*com|automation|automatiser|workflow/i.test(text)) matched = 'automate';
  else if (/\/scrape|scraper|extraction|données/i.test(text)) matched = 'scrape';
  else if (/\/search|recherche|chercher/i.test(text)) matched = 'search';
  else if (/\/security|sécurité|audit code|vulnérabilité/i.test(text)) matched = 'security';
  else if (/\/lex|aspect légal|conformité|juridique/i.test(text)) matched = 'lex';
  else if (/\/present|diaporama|presentation|keynote/i.test(text)) matched = 'present';

  const isBlueprintMode = /^\/[a-z]+\s*$/i.test(text.trim());
  return (matched && SKILLS[matched]) ? (isBlueprintMode ? `TEMPLATE_${matched}` : matched) : null;
}

